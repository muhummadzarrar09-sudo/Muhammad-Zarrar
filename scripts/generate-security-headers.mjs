import fs from "fs";
import path from "path";
import crypto from "crypto";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");

const SITE_URL = "https://muhummadzarrar.vercel.app";

// Read index.html and extract JSON-LD bytes between tags
const indexPath = path.join(root, "index.html");
const indexRaw = fs.readFileSync(indexPath);
const startTag = Buffer.from('<script type="application/ld+json">');
const endTag = Buffer.from("</script>");
const startIdx = indexRaw.indexOf(startTag);
const contentStart = startIdx + startTag.length;
const endIdx = indexRaw.indexOf(endTag, contentStart);
const jsonLdBytes = indexRaw.subarray(contentStart, endIdx);
const hash = crypto.createHash("sha256").update(jsonLdBytes).digest("base64");
const expectedHash = `sha256-${hash}`;
console.log(`Computed JSON-LD hash: ${expectedHash}`);

// CSP templates
const cspCore = `default-src 'self'; base-uri 'self'; object-src 'none'; script-src 'self' '${expectedHash}'; style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src 'self' https://fonts.gstatic.com data:; img-src 'self' data: https://avatars.githubusercontent.com; connect-src 'self'; media-src 'self'; worker-src 'self' blob:; form-action 'self' mailto: https://wa.me; upgrade-insecure-requests`;
const cspWithFrame = `default-src 'self'; base-uri 'self'; object-src 'none'; frame-ancestors 'none'; script-src 'self' '${expectedHash}'; style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src 'self' https://fonts.gstatic.com data:; img-src 'self' data: https://avatars.githubusercontent.com; connect-src 'self'; media-src 'self'; worker-src 'self' blob:; form-action 'self' mailto: https://wa.me; upgrade-insecure-requests`;

// Update csp.ts source of truth
const cspPath = path.join(root, "src/lib/csp.ts");
const cspContent = `// Single source of truth for Content Security Policy
// Auto-generated by scripts/generate-security-headers.mjs - DO NOT EDIT MANUALLY
// Hash is for the inline application/ld+json script in index.html
// Computed as base64(sha256(bytes between <script type="application/ld+json"> and </script>))
export const CSP_JSON_LD_HASH = "${expectedHash}";

export const CSP_POLICY_CORE =
  \`${cspCore}\`;

export const CSP_POLICY_WITH_FRAME = \`\${CSP_POLICY_CORE.replace("object-src 'none';", "object-src 'none'; frame-ancestors 'none';")}\`;

// For index.html meta tag (allows same as core)
export const CSP_META = CSP_POLICY_CORE;

// For hosting headers (adds frame-ancestors)
export const CSP_HEADER = \`${cspWithFrame}\`;
`;
fs.writeFileSync(cspPath, cspContent);
console.log("Updated src/lib/csp.ts");

// Update vercel.json
const vercelPath = path.join(root, "vercel.json");
const vercel = {
  headers: [
    {
      source: "/(.*)",
      headers: [
        { key: "Content-Security-Policy", value: cspWithFrame },
        { key: "X-Content-Type-Options", value: "nosniff" },
        { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
        { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(), payment=(), usb=()" },
        { key: "X-Frame-Options", value: "DENY" }
      ]
    }
  ]
};
fs.writeFileSync(vercelPath, JSON.stringify(vercel, null, 2) + "\n");
console.log("Updated vercel.json");

// Update public/_headers
const headersPath = path.join(root, "public/_headers");
const headersContent = `/*
  Content-Security-Policy: ${cspWithFrame}
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()
  X-Frame-Options: DENY
`;
fs.writeFileSync(headersPath, headersContent);
console.log("Updated public/_headers");

// Update index.html meta CSP
let indexHtml = fs.readFileSync(indexPath, "utf8");
indexHtml = indexHtml.replace(
  /<meta http-equiv="Content-Security-Policy" content="[^"]*" \/>/,
  `<meta http-equiv="Content-Security-Policy" content="${cspCore}" />`
);
fs.writeFileSync(indexPath, indexHtml);
console.log("Updated index.html CSP meta");

// Update robots.txt and sitemap.xml from SITE_URL
const robotsPath = path.join(root, "public/robots.txt");
fs.writeFileSync(robotsPath, `User-agent: *\nAllow: /\n\nSitemap: ${SITE_URL}/sitemap.xml\n`);
console.log("Updated robots.txt");

const sitemapPath = path.join(root, "public/sitemap.xml");
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <url>
    <loc>${SITE_URL}/</loc>
    <changefreq>monthly</changefreq>
    <priority>1.0</priority>
  </url>
  <url>
    <loc>${SITE_URL}/business</loc>
    <changefreq>monthly</changefreq>
    <priority>0.9</priority>
  </url>
</urlset>
`;
fs.writeFileSync(sitemapPath, sitemap);
console.log("Updated sitemap.xml");

console.log("All security headers and SEO files synced from single source of truth.");
